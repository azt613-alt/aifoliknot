def main():
    if not DATABASE_URL:
        print("DATABASE_URL is missing.")
        return

    conn = psycopg2.connect(DATABASE_URL)
    cur = conn.cursor()

    print("🧹 מנקה נתונים ישנים...")
    cur.execute("DELETE FROM store_prices;")
    cur.execute("DELETE FROM stores;")
    cur.execute("DELETE FROM products;")
    cur.execute("DELETE FROM chains;")

    # 1. הזנת רשתות
    execute_batch(cur, "INSERT INTO chains (chain_id, chain_name) VALUES (%s, %s);", ALL_CHAINS)

    # 2. הזנת סניפים
    print(f"📦 מזין {len(EXPANDED_STORES)} סניפים אמיתיים בפריסה ארצית מלאה...")
    execute_batch(cur, """
        INSERT INTO stores (chain_id, store_id, store_name, address, lat, lon)
        VALUES (%s, %s, %s, %s, %s, %s);
    """, EXPANDED_STORES)

    # 3. הזנת מוצרים
    products = [(code, name, mfr) for code, name, mfr, _ in CORE_PRODUCTS]
    execute_batch(cur, "INSERT INTO products (item_code, item_name, manufacturer_name) VALUES (%s, %s, %s);", products)

    # 4. מחירון לכל הסניפים
    price_multipliers = {
        "7290027600007": 1.05,  # שופרסל
        "7290058140886": 0.94,  # רמי לוי
        "7290803800003": 0.95,  # יוחננוף
        "7290696200003": 0.98,  # ויקטורי
        "7290725900003": 1.02,  # קרפור
        "7290103152017": 0.92,  # אושר עד
        "7290873255550": 1.10,  # טיב טעם
        "7290661400001": 0.96   # מחסני השוק
    }

    all_prices = []
    for chain_id, store_id, _, _, _, _ in EXPANDED_STORES:
        mult = price_multipliers.get(chain_id, 1.0)
        for code, _, _, base_p in CORE_PRODUCTS:
            final_p = round(base_p * mult, 2)
            all_prices.append((chain_id, store_id, code, final_p))

    print(f"💰 מזין {len(all_prices)} רשומות מחיר...")
    execute_batch(cur, """
        INSERT INTO store_prices (chain_id, store_id, item_code, item_price, price_update_date)
        VALUES (%s, %s, %s, %s, CURRENT_TIMESTAMP);
    """, all_prices, page_size=1000)

    conn.commit()
    cur.close()
    conn.close()
    print("✨ הסנכרון הארצי הושלם בהצלחה!")

if __name__ == "__main__":
    main()
