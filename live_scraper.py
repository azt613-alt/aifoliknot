def fetch_shufersal_stores_file():
    """הורדה ופריקה חיה של קובץ הסניפים הרשמי של שופרסל"""
    stores = []
    try:
        url = "http://prices.shufersal.co.il/FileServer/Stores"
        print("🌐 סורק פורטל קבצים רשמי של שופרסל לקבלת קובץ Stores...")
        res = requests.get(url, timeout=15)
        matches = re.findall(r'href=[\'"]?([^\'" >]+Stores[^\'" >]*\.gz)', res.text, re.IGNORECASE)
        
        if not matches:
            print("⚠️ לא נמצא קובץ Stores בשרת ה-HTTP של שופרסל.")
            return stores

        file_url = matches[-1]
        if not file_url.startswith("http"):
            file_url = f"http://prices.shufersal.co.il{file_url}"

        print(f"📥 מוריד קובץ סניפים רשמי: {file_url}")
        res_file = requests.get(file_url, stream=True, timeout=30)

        if res_file.status_code == 200 and res_file.content.startswith(b'\x1f\x8b'):
            with gzip.GzipFile(fileobj=res_file.raw) as gz:
                tree = etree.parse(gz)
                root = tree.getroot()
                
                # חיפוש תגיות Store
                store_nodes = root.xpath('.//Store') or root.xpath('.//STORE')
                for node in store_nodes:
                    s_id = node.findtext("StoreId") or node.findtext("STOREID") or ""
                    s_name = node.findtext("StoreName") or node.findtext("STORENAME") or ""
                    address = node.findtext("Address") or node.findtext("ADDRESS") or ""
                    city = node.findtext("City") or node.findtext("CITY") or ""

                    s_id = s_id.strip()
                    s_name = clean_text(s_name)
                    address = clean_text(address)
                    city = clean_text(city)

                    if s_id and s_name:
                        full_address = f"{address}, {city}".strip(", ")
                        lat, lon = get_city_lat_lon(city, address)
                        stores.append(("7290027600007", s_id, s_name, full_address, lat, lon))

                print(f"✅ פוענחו בהצלחה {len(stores)} סניפים רשמיים של שופרסל מה-XML.")
    except Exception as e:
        print(f"⚠️ שגיאה במשיכת קובץ הסניפים של שופרסל: {e}")
    return stores

